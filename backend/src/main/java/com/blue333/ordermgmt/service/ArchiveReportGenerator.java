package com.blue333.ordermgmt.service;

import com.lowagie.text.Document;
import com.lowagie.text.DocumentException;
import com.lowagie.text.Font;
import com.lowagie.text.PageSize;
import com.lowagie.text.Paragraph;
import com.lowagie.text.Phrase;
import com.lowagie.text.pdf.BaseFont;
import com.lowagie.text.pdf.PdfPCell;
import com.lowagie.text.pdf.PdfPTable;
import com.lowagie.text.pdf.PdfWriter;
import java.awt.Color;
import java.io.ByteArrayOutputStream;
import java.time.format.DateTimeFormatter;
import java.util.List;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;

/**
 * A-19/A-28: renders the delivery-archive timeline as a PDF with OpenPDF (chosen over iText's AGPL
 * build). Labels are English so the report is readable even with the built-in Helvetica font; a CJK
 * TrueType font can be embedded through {@code app.archive-report.font-path} to render Chinese data.
 */
@Component
public class ArchiveReportGenerator {
  private static final DateTimeFormatter DATE_TIME = DateTimeFormatter.ofPattern("yyyy-MM-dd HH:mm");
  private static final int MAX_CELL_LENGTH = 2000;

  private final BaseFont baseFont;

  public ArchiveReportGenerator(@Value("${app.archive-report.font-path:}") String fontPath) {
    this.baseFont = loadFont(fontPath);
  }

  public byte[] generate(ArchiveReportData data) {
    ByteArrayOutputStream output = new ByteArrayOutputStream();
    Document document = new Document(PageSize.A4, 36, 36, 36, 36);
    try {
      PdfWriter.getInstance(document, output);
      document.open();
      document.addTitle("Delivery Archive Report " + data.orderNo());
      document.add(new Paragraph("Delivery Archive Report", font(18, Font.BOLD)));
      document.add(new Paragraph("Order " + data.orderNo(), font(12, Font.NORMAL)));
      document.add(new Paragraph("Generated by order-mgmt · snapshot of the closed delivery loop", font(9, Font.ITALIC)));
      document.add(new Paragraph(" "));

      addSummary(document, data);
      addTasks(document, data.tasks());
      addVersions(document, data.versions());
      addClientReviews(document, data.clientReviews());
      addFeedbacks(document, data.feedbacks());
      addConfirmation(document, data.confirmation());
      addExceptions(document, data.exceptions());
      addTimeline(document, data.timeline());

      document.close();
      return output.toByteArray();
    } catch (DocumentException exception) {
      throw new IllegalStateException("Could not generate the delivery archive PDF", exception);
    } finally {
      if (document.isOpen()) {
        document.close();
      }
    }
  }

  private void addSummary(Document document, ArchiveReportData data) throws DocumentException {
    document.add(section("1. Order summary"));
    PdfPTable table = table(2, 100);
    addLabelValue(table, "Customer", data.customerName());
    addLabelValue(table, "Use scene", data.useScene());
    addLabelValue(table, "Delivery deadline", data.deliveryDeadline() == null ? null : data.deliveryDeadline().toString());
    addLabelValue(table, "Status", data.orderStatus());
    addLabelValue(table, "Account manager", data.accountManager());
    addLabelValue(table, "Created at", format(data.createdAt()));
    addLabelValue(table, "Remark", data.remark());
    document.add(table);
  }

  private void addTasks(Document document, List<ArchiveReportData.TaskRow> tasks) throws DocumentException {
    document.add(section("2. Material tasks"));
    List<List<String>> rows = tasks.stream().map(task -> List.of(
        orDash(task.materialType()), orDash(task.specSize()), orDash(task.assignee()),
        orDash(task.priority()), orDash(task.status()), format(task.deadline()))).toList();
    document.add(dataTable(new float[] {1.2f, 1.4f, 1.4f, 0.9f, 1.3f, 1.5f},
        List.of("Material", "Spec", "Designer", "Priority", "Status", "Deadline"), rows));
  }

  private void addVersions(Document document, List<ArchiveReportData.VersionRow> versions)
      throws DocumentException {
    document.add(section("3. Design versions"));
    List<List<String>> rows = versions.stream().map(version -> List.of(
        orDash(version.versionNo()), orDash(version.materialType()), orDash(version.specSize()),
        orDash(version.status()), orDash(version.uploader()), format(version.submittedAt()),
        version.overdue() ? "YES" : "NO")).toList();
    document.add(dataTable(new float[] {0.8f, 1.1f, 1.2f, 1.5f, 1.4f, 1.5f, 0.7f},
        List.of("Version", "Material", "Spec", "Status", "Uploader", "Submitted", "Overdue"), rows));
  }

  private void addClientReviews(Document document, List<ArchiveReportData.ClientReviewRow> reviews)
      throws DocumentException {
    document.add(section("4. Client reviews"));
    List<List<String>> rows = reviews.stream().map(review -> List.of(
        orDash(review.versionNo()), orDash(review.status()), orDash(review.initiator()),
        format(review.startedAt()), format(review.completedAt()))).toList();
    document.add(dataTable(new float[] {0.9f, 1.1f, 1.4f, 1.5f, 1.5f},
        List.of("Version", "Status", "Initiator", "Started", "Completed"), rows));
  }

  private void addFeedbacks(Document document, List<ArchiveReportData.FeedbackRow> feedbacks)
      throws DocumentException {
    document.add(section("5. Feedback items"));
    List<List<String>> rows = feedbacks.stream().map(item -> List.of(
        orDash(item.feedbackNo()), orDash(item.versionNo()), orDash(item.type()),
        orDash(item.source()), orDash(item.status()), orDash(item.createdBy()),
        orDash(item.content()))).toList();
    document.add(dataTable(new float[] {0.9f, 0.8f, 1.5f, 0.9f, 1.0f, 1.1f, 2.5f},
        List.of("No.", "Version", "Type", "Source", "Status", "Created by", "Content"), rows));
  }

  private void addConfirmation(Document document, ArchiveReportData.ConfirmationRow confirmation)
      throws DocumentException {
    document.add(section("6. Client confirmation"));
    if (confirmation == null) {
      document.add(new Paragraph("No confirmation record.", font(10, Font.NORMAL)));
      return;
    }
    PdfPTable table = table(2, 100);
    addLabelValue(table, "Version", confirmation.versionNo());
    addLabelValue(table, "Confirmer", confirmation.confirmerName());
    addLabelValue(table, "Confirmed at", format(confirmation.confirmedAt()));
    document.add(table);
  }

  private void addExceptions(Document document, List<ArchiveReportData.ExceptionRow> exceptions)
      throws DocumentException {
    document.add(section("7. Exception records"));
    if (exceptions == null || exceptions.isEmpty()) {
      document.add(new Paragraph("No exception record.", font(10, Font.NORMAL)));
      return;
    }
    List<List<String>> rows = exceptions.stream().map(record -> List.of(
        orDash(record.type()), orDash(record.status()), orDash(record.recorder()),
        orDash(record.description()), orDash(record.resolution()), format(record.createdAt()))).toList();
    document.add(dataTable(new float[] {0.9f, 1.1f, 0.9f, 2.6f, 2.2f, 1.4f},
        List.of("Type", "Status", "Recorder", "Description", "Resolution", "Created"), rows));
  }

  private void addTimeline(Document document, List<ArchiveReportData.TimelineRow> timeline)
      throws DocumentException {
    document.add(section("8. Operation timeline"));
    List<List<String>> rows = timeline.stream().map(this::timelineRow).toList();
    document.add(dataTable(new float[] {1.6f, 1.5f, 1.2f, 1.8f, 2.2f, 1.0f},
        List.of("Time", "Action", "Operator", "Target", "State transition", "Result"), rows));
  }

  private List<String> timelineRow(ArchiveReportData.TimelineRow entry) {
    return List.of(format(entry.at()), orDash(entry.action()), orDash(entry.operator()),
        orDash(entry.target()), orDash(entry.state()), orDash(entry.result()));
  }

  private Paragraph section(String title) {
    Paragraph paragraph = new Paragraph(title, font(13, Font.BOLD));
    paragraph.setSpacingBefore(10);
    paragraph.setSpacingAfter(4);
    return paragraph;
  }

  private static PdfPTable table(int columns, float widthPercentage) {
    PdfPTable table = new PdfPTable(columns);
    table.setWidthPercentage(widthPercentage);
    return table;
  }

  private void addLabelValue(PdfPTable table, String label, String value) {
    PdfPCell labelCell = new PdfPCell(new Phrase(label, font(9, Font.BOLD)));
    labelCell.setBackgroundColor(new Color(238, 238, 238));
    table.addCell(labelCell);
    table.addCell(new PdfPCell(new Phrase(orDash(value), font(9, Font.NORMAL))));
  }

  private PdfPTable dataTable(float[] widths, List<String> headers, List<List<String>> rows) {
    PdfPTable table = new PdfPTable(widths);
    table.setWidthPercentage(100);
    for (String header : headers) {
      PdfPCell cell = new PdfPCell(new Phrase(header, font(8, Font.BOLD)));
      cell.setBackgroundColor(new Color(238, 238, 238));
      table.addCell(cell);
    }
    for (List<String> row : rows) {
      row.forEach(value -> table.addCell(new PdfPCell(new Phrase(value, font(8, Font.NORMAL)))));
    }
    if (rows.isEmpty()) {
      PdfPCell empty = new PdfPCell(new Phrase("None", font(8, Font.NORMAL)));
      empty.setColspan(headers.size());
      table.addCell(empty);
    }
    return table;
  }

  private Font font(float size, int style) {
    return new Font(baseFont, size, style);
  }

  private static String format(java.time.LocalDateTime value) {
    return value == null ? "-" : DATE_TIME.format(value);
  }

  private static String orDash(String value) {
    if (value == null || value.isBlank()) {
      return "-";
    }
    String singleLine = value.replace('\r', ' ').replace('\n', ' ');
    return singleLine.length() <= MAX_CELL_LENGTH ? singleLine : singleLine.substring(0, MAX_CELL_LENGTH) + "...";
  }

  private static BaseFont loadFont(String fontPath) {
    if (fontPath != null && !fontPath.isBlank()) {
      try {
        return BaseFont.createFont(fontPath, BaseFont.IDENTITY_H, BaseFont.EMBEDDED);
      } catch (Exception exception) {
        throw new IllegalStateException("Could not load archive report font: " + fontPath, exception);
      }
    }
    try {
      return BaseFont.createFont(BaseFont.HELVETICA, BaseFont.WINANSI, BaseFont.NOT_EMBEDDED);
    } catch (Exception exception) {
      throw new IllegalStateException("Could not load the default archive report font", exception);
    }
  }
}
